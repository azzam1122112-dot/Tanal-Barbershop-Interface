import { addRiyadhDays, startOfRiyadhDay } from "@/lib/datetime/riyadh";

/**
 * نافذة جلب المواعيد لفحص التداخل.
 *
 * **لماذا ملف مستقل:** أربعة مواضع تفحص التداخل (شبكة الفترات، تحقّق الفترة،
 * معاملة حجز العميل، وحارس تداخل الموظف)، وكلها كانت تجلب **يوم رياض واحدًا**
 * ثم تحسب التقاطع في Node لأن المدة عمود لا تعبير SQL. الجلب بيوم واحد يفترض
 * ضمنًا أن كل موعد يبدأ وينتهي داخل يومه — وهو افتراض يسقط مع المدد الطويلة:
 * موعد يبدأ 11:30 مساءً بمدة ساعتين ينتهي 1:30 صباحًا، فلا يظهر في استعلام
 * اليوم التالي ويُحجز فوقه. حجز العميل محصّن صدفةً (`isBarberOnDuty` يمنع
 * تجاوز نهاية الدوام)، لكن `createAppointment` للموظف لا يفحص الدوام إطلاقًا.
 *
 * الحل: توسيع **الحدّ الأدنى** للنافذة بمقدار أقصى مدة مسموحة، فيدخل أي موعد
 * سابق قد يمتد إلى المدى. الحدّ الأعلى يبقى كما هو: موعد يبدأ بعد نهاية مدانا
 * لا يمكن أن يتقاطع معه.
 */

/**
 * أقصى مدة لموعد واحد. سقفٌ للتحقق **ومقدارُ توسيع نافذة البحث معًا** —
 * ربطهما في ثابت واحد يمنع أن يرفع أحدهما دون الآخر فتعود الثغرة صامتة.
 */
export const MAX_APPOINTMENT_MINUTES = 8 * 60;

/** بداية النافذة: أول يوم المدى ناقص أقصى مدة، فيُلتقط الممتدّ من قبله. */
export function overlapWindowStart(rangeStart: Date) {
  return new Date(rangeStart.getTime() - MAX_APPOINTMENT_MINUTES * 60_000);
}

/**
 * نافذة يوم الرياض الذي يقع فيه `at`، موسّعة للخلف.
 * الحدّ الأعلى يوم كامل بعد بداية اليوم: موعد يبدأ بعده لا يلامس أي وقت فيه.
 */
export function dayOverlapWindow(at: Date) {
  const dayStart = startOfRiyadhDay(at);
  return { gte: overlapWindowStart(dayStart), lt: addRiyadhDays(dayStart, 1) };
}
