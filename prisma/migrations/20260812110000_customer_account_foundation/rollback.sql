-- مرجع تراجع للبيئات المحلية فقط — **ليس خطة تراجع للإنتاج**.
--
-- ===================== خطة التراجع في الإنتاج =====================
-- 1) أعِد نشر الكود السابق إن لزم.
-- 2) **اترك `CustomerAccount` و`Customer.accountId` قائمين.** الهجرة إضافية
--    بحتة، والكود السابق لا يقرأ أيًّا منهما — فوجودهما بلا أثر تشغيلي ولا
--    أداء، وإسقاطهما لا يشتري شيئًا.
-- 3) إن صار حذف البنية مطلوبًا فعلًا، اكتب **هجرة عكسية مدروسة** تُراجَع وتُطبَّق
--    بـ `prisma migrate deploy` كأي هجرة أخرى.
--
-- **لا تحذف صفًا من `_prisma_migrations` يدويًا على بيئة مشتركة.** تاريخ
-- الهجرات سجل مشترك بين كل من ينشر: حذف صف منه يجعل Prisma يظن أن الهجرة لم
-- تُطبَّق فيعيد تطبيقها على قاعدة طُبِّقت عليها، ويكسر `migrate diff` لكل من
-- يعمل على الفرع نفسه. ولا تُعدَّل هجرة سبق أن طُبِّقت على بيئة مشتركة —
-- التصحيح يكون بهجرة تالية لا بتحرير الماضي.
--
-- ما تحت هذا السطر صالح لقاعدة تطوير محلية لم تُشارَك، ولا يمسّ أي جدول قديم:
-- `Customer` يعود إلى أعمدته السابقة حرفيًا، ولا صف من الزيارات أو النقاط
-- أو المواعيد يتغيّر.

ALTER TABLE "Customer" DROP CONSTRAINT IF EXISTS "Customer_accountId_fkey";
DROP INDEX IF EXISTS "Customer_accountId_organizationId_key";
ALTER TABLE "Customer" DROP COLUMN IF EXISTS "accountId";

DROP TABLE IF EXISTS "CustomerAccount";
DROP TYPE IF EXISTS "CustomerAccountStatus";
